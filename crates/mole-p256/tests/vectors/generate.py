#!/usr/bin/env python3
"""Independent hashlib/integer oracle for the MOLE P-256 derivation vectors.

The XMD implementation follows RFC 9380 sections 5.3.1 and 5.3.3 and is
checked against Appendix K.1 before generating anything. This script imports
no Rust implementation and performs reduction with Python integer arithmetic.
Assisted by ChatGPT.
"""
from __future__ import annotations

import argparse
from hashlib import sha256
from pathlib import Path

ORDER = int("ffffffff00000000ffffffffffffffffbce6faada7179e84f3b9cac2fc632551", 16)
SEED = bytes(range(48))
SECRET = bytes(range(32))
# The last context makes every tag longer than 255 bytes (RFC 9380, 5.3.3).
CONTEXTS = (b"EC-ACTv1-P256-SHA256", b"EC-IHATv1-P256-SHA256", b"x" * 300)
# Tag lengths around the 255-byte limit, for expand_message_xmd itself.
TAG_LENGTHS = (255, 256, 512)


def xmd(message: bytes, dst: bytes, length: int) -> bytes:
    if not 0 <= length <= 255 * 32:
        raise ValueError("invalid XMD output length")
    if len(dst) > 255:
        dst = sha256(b"H2C-OVERSIZE-DST-" + dst).digest()
    tag = dst + bytes([len(dst)])
    b0 = sha256(bytes(64) + message + length.to_bytes(2, "big") + b"\0" + tag).digest()
    blocks: list[bytes] = []
    previous = bytes(32)
    for counter in range(1, (length + 31) // 32 + 1):
        previous = sha256(bytes(a ^ b for a, b in zip(b0, previous)) + bytes([counter]) + tag).digest()
        blocks.append(previous)
    return b"".join(blocks)[:length]


def scalar(message: bytes, dst: bytes) -> str:
    return (int.from_bytes(xmd(message, dst, 48), "big") % ORDER).to_bytes(32, "big").hex()


def expand(context: bytes, key: bytes, count: int) -> list[str]:
    return [scalar(key + index.to_bytes(4, "big"), b"ExpandScalars-" + context) for index in range(count)]


def derive_scalars(context: bytes) -> list[str]:
    info = b"test"
    key = xmd(SEED + len(info).to_bytes(2, "big") + info, b"DeriveScalars-" + context, 32)
    return expand(context, key, 3)


def derive_nonces(context: bytes) -> list[str]:
    def pad(data: bytes) -> bytes:
        return data + bytes(-len(data) % 64)
    label, instance = b"nonce", b"review-fixture"
    message = (pad(SEED) + pad(len(SECRET).to_bytes(4, "big") + SECRET)
               + len(label).to_bytes(2, "big") + label
               + len(instance).to_bytes(4, "big") + instance)
    return expand(context, xmd(message, b"DeriveNonces-" + context, 32), 3)


def key_scalar(context: bytes) -> str:
    info = b"GenerateKeyPair"
    message = SEED + len(info).to_bytes(2, "big") + info
    for counter in range(256):
        result = scalar(message + bytes([counter]), b"DeriveKeyPair-" + context)
        if int(result, 16):
            return result
    raise ValueError("no nonzero key scalar")


def rust_bytes(value: bytes) -> str:
    if len(set(value)) == 1 and len(value) > 32:
        return f"&[b'{chr(value[0])}'; {len(value)}]"
    return f'b"{value.decode()}"'


def render() -> str:
    dst = b"QUUX-V01-CS02-with-expander-SHA256-128"
    assert xmd(b"", dst, 32).hex() == "68a985b87eb6b46952128911f2a4412bbc302a9d759667f87f7a21d803f07235"
    assert xmd(b"abc", dst, 32).hex() == "d8ccab23b5985ccea865c6c97b6e5b8350e794e603b4b97902f53a8a0d605615"
    expected = (
        "af84c27ccfd45d41914fdff5df25293e221afc53d8ad2ac06d5e3e29485dadbee0"
        "d121587713a3e0dd4d5e69e93eb7cd4f5df4cd103e188cf60cb02edc3edf18e"
        "da8576c412b18ffb658e3dd6ec849469b979d444cf7b26911a08e63cf31f9d"
        "cc541708d3491184472c2c29bb749d4286b004ceb5ee6b9a7fa5b646c993f0ced"
    )
    assert xmd(b"", dst, 128).hex() == expected
    lines = [
        "// Generated by tests/vectors/generate.py; do not edit by hand.",
        "// Independent hashlib/integer reference; Assisted by ChatGPT.",
        "",
        "struct DerivationVector {",
        "    context: &'static [u8],",
        "    scalar: &'static str,",
        "    scalars: [&'static str; 3],",
        "    nonces: [&'static str; 3],",
        "    key: &'static str,",
        "}",
        "",
        f"const DERIVATION_VECTORS: [DerivationVector; {len(CONTEXTS)}] = [",
    ]
    for context in CONTEXTS:
        lines.extend([
            "    DerivationVector {",
            f"        context: {rust_bytes(context)},",
            f'        scalar: "{scalar(b"example", b"HashToScalar-" + context)}",',
            "        scalars: [",
        ])
        lines.extend(f'            "{value}",' for value in derive_scalars(context))
        lines.extend(["        ],", "        nonces: ["])
        lines.extend(f'            "{value}",' for value in derive_nonces(context))
        lines.extend(["        ],", f'        key: "{key_scalar(context)}",', "    },"])
    lines.extend([
        "];",
        "",
        "/// `expand_message_xmd(\"abc\", \"x\" * length, 48)`.",
        f"const TAG_VECTORS: [(usize, &str); {len(TAG_LENGTHS)}] = [",
    ])
    for length in TAG_LENGTHS:
        output = xmd(b"abc", b"x" * length, 48).hex()
        lines.extend([
            "    (",
            f"        {length},",
            f'        concat!("{output[:64]}", "{output[64:]}"),',
            "    ),",
        ])
    lines.extend(["];", ""])
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = Path(__file__).resolve().parent / "derivations.rs"
    expected = render()
    if args.check:
        if target.read_text() != expected:
            raise SystemExit("derivation_vectors.rs differs from the independent reference")
        print("Independent derivation vectors and RFC 9380 self-tests pass.")
    else:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(expected)
        print(f"Wrote {target}")


if __name__ == "__main__":
    main()
